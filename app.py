# UN CERTIFICATE CROSS-VERIFICATION
# ============================================================================

MARKING_CODE_RE = re.compile(r"([0-9][A-Z][0-9A-Z]?/[A-Z]\s*[0-9*]+/S/[0-9A-Z*]+)", re.I)
MARKING_IND_RE = re.compile(r"(IND/(?:[A-Z]/)?[0-9]+)", re.I)
VALID_RE = re.compile(r"valid\s*upto\s*[:\-]?\s*(\d{1,2}\s+[A-Za-z]+\s+\d{4})", re.I)


def extract_cert_info(text):
    # The packing-code fragment (e.g. "4G/Y 18/S/25") and the "IND/xxxxx" ref
    # are searched independently and then combined: real-world PDF text
    # extraction often interleaves the "UN Marking alloted :" label between
    # the two value lines, so they can't be relied on to sit adjacent.
    code_m = MARKING_CODE_RE.search(text)
    ind_m = MARKING_IND_RE.search(text)
    if not code_m or not ind_m:
        return None
    code_part = re.sub(r"\s+", " ", code_m.group(1)).strip()
    full = f"{code_part} {ind_m.group(1)}"
    digits = re.search(r"(\d+)$", ind_m.group(1))
    digits = digits.group(1) if digits else ""
    short_cert = digits[-4:] if digits else ""
    valid_m = VALID_RE.search(text)
    valid_upto = valid_m.group(1) if valid_m else None
    return {"full": full, "shortCert": short_cert, "validUpto": valid_upto}


def norm_marking(s):
    return re.sub(r"\s+", " ", str(s or "").upper()).strip()


def parse_cert_date(s):
    if not s:
        return None
    try:
        return datetime.strptime(s, "%d %b %Y").date()
    except ValueError:
        try:
            return datetime.strptime(s, "%d %B %Y").date()
        except ValueError:
            return None


def verify_cert_against_row(cert_info, row, today):
    checks = []
    marking_ok = norm_marking(cert_info["full"]) == norm_marking(row["unCertNo1"])
    checks.append({"field": "UN marking string", "ok": marking_ok, "expected": row["unCertNo1"], "found": cert_info["full"]})
    if row["unCertNoShort"]:
        short_ok = cert_info["shortCert"] == row["unCertNoShort"].strip()
        checks.append({"field": "Certificate ref.", "ok": short_ok, "expected": row["unCertNoShort"], "found": cert_info["shortCert"]})
    if cert_info["validUpto"]:
        valid_date = parse_cert_date(cert_info["validUpto"])
        expired = valid_date is not None and valid_date < today
        checks.append({
            "field": "Validity",
            "ok": not expired,
            "expected": "not expired",
            "found": cert_info["validUpto"] + (" (EXPIRED)" if expired else " (valid)"),
        })
    return checks


