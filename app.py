"""
DG Declaration Builder
=======================
Reads a DG cargo Annexure (Excel), optionally cross-verifies it against MSDS
and UN Certificate PDFs, groups product lines onto declarations using a
5-checkpoint sequence, and fills your own DGDI Excel template — one file per
declaration group — ready to submit to your shipping line.

The output is generated by editing your real template workbook in place
(openpyxl), so fonts, borders, merged cells, column widths and any embedded
letterhead/logo are preserved exactly. Only the specific data cells are
overwritten.

USAGE
-----
    python dg_declaration_builder.py \\
        --annexure Annexure.xlsx \\
        --template MANUAL_DGD1.xlsx \\
        --msds MSDS1.pdf MSDS2.pdf \\
        --certs CERT1.pdf CERT2.pdf \\
        --shipment shipment.json \\
        --out ./output

Run with --make-shipment-template to generate a blank shipment.json to fill in.
Run with --help for all options.
"""

