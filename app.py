def packing_prefix(cert_str):
    s = str(cert_str or "").strip().upper()
    if s.startswith("4G"):
        return "BOX_4G"
    if s.startswith("1A1"):
        return "DRUM_1A1"
    if s.startswith("1A2"):
        return "DRUM_1A2"
    m = re.match(r"^[0-9][A-Z][0-9]?", s)
    return m.group(0) if m else s[:3]


def compute_group_key(row, threshold):
    fp = extract_flash_number(row["flashPoint"])
    bucket = "LT" if (fp is not None and fp < threshold) else "GE"
    psn = row["psn"].upper()
    pkg_code = packing_prefix(row["unCertNo1"])
    mp = row["marinePollutant"]
    un = row["unNumber"]
    return (bucket, psn, pkg_code, mp, un)


def round_up2(n):
    """ROUNDUP-style rounding to 2 decimals, immune to float drift from
    repeated addition. Never understates a shipping weight."""
    fixed = round(n * 1e6) / 1e6
    import math
    return math.ceil(fixed * 100 - 1e-6) / 100


def uniq(items):
    seen = []
    for x in items:
        x = str(x).strip()
        if x and x not in seen:
            seen.append(x)
    return seen


def aggregate_group(rows):
    min_flash = None
    for r in rows:
        fp = extract_flash_number(r["flashPoint"])
        if fp is not None and (min_flash is None or fp < min_flash[0]):
            min_flash = (fp, r["flashPoint"])

    pfx = packing_prefix(rows[0]["unCertNo1"])
    is_drum = pfx.startswith("DRUM")
    pkg_label = "DRUMS" if is_drum else "BOXES"

    outer_total = sum(r["noOfBoxes"] for r in rows)
    inner_total = sum(r["noInTins"] for r in rows)
    gross_total = round_up2(sum(r["grossWt"] for r in rows))
    net_total = round_up2(sum(r["netWt"] for r in rows))

    return {
        "rows": rows,
        "unNumber": rows[0]["unNumber"],
        "psn": rows[0]["psn"],
        "hazClass": rows[0]["hazClass"],
        "pkgGroup": rows[0]["pkgGroup"],
        "marinePollutant": rows[0]["marinePollutant"],
        "ems": ", ".join(uniq(r["ems"] for r in rows)),
        "technicalName": " , ".join(uniq(r["technicalName"] for r in rows)),
        "flashPoint": min_flash[1] if min_flash else "",
        "unPackingCode": " , ".join(uniq(r["unCertNo1"] for r in rows)),
        "outerPackages": f"{outer_total:g} {pkg_label}",
        "isDrum": is_drum,
        "innerPacking": None if is_drum else f"{inner_total:g} TINS",
        "grossWt": f"{gross_total:.2f} KGS",
        "netWt": f"{net_total:.2f} KGS",
        "materials": [r["materialDescription"] for r in rows],
    }


def compute_groups(rows, threshold):
    by_key = {}
    for row in rows:
        key = compute_group_key(row, threshold)
        by_key.setdefault(key, []).append(row)
    return [aggregate_group(rs) for rs in by_key.values()]


