def set_cell(ws, addr, value):
    if value in (None, ""):
        ws[addr] = None
        return
    sval = str(value).strip()
    is_num = re.fullmatch(r"-?[0-9]+(\.[0-9]+)?", sval) is not None
    ws[addr] = float(sval) if ("." in sval and is_num) else (int(sval) if is_num else value)


