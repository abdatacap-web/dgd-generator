def load_shipment(path):
    if not path:
        return {k: "" for k in SHIPMENT_FIELDS}
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return {k: data.get(k, "") for k in SHIPMENT_FIELDS}


def write_shipment_template(path):
    template = {k: "" for k in SHIPMENT_FIELDS}
    template["shipperBlock"] = "COMPANY NAME\nADDRESS LINE 1\nADDRESS LINE 2\nCOUNTRY"
    template["consigneeBlock"] = "COMPANY NAME\nADDRESS LINE 1\nADDRESS LINE 2\nCOUNTRY"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(template, f, indent=2)
    print(f"Wrote blank shipment template to {path}")


def main():
    ap = argparse.ArgumentParser(description="DG Declaration Builder")
    ap.add_argument("--annexure", help="Path to the Annexure Excel file")
    ap.add_argument("--template", help="Path to the blank DGDI Excel template")
    ap.add_argument("--msds", nargs="*", default=[], help="MSDS PDF file(s)")
    ap.add_argument("--certs", nargs="*", default=[], help="UN Certificate PDF file(s)")
    ap.add_argument("--shipment", help="Path to a shipment.json (see --make-shipment-template)")
    ap.add_argument("--out", default="./output", help="Output directory (default ./output)")
    ap.add_argument("--threshold", type=float, default=23.0, help="Flash point bucket threshold, degC (default 23)")
    ap.add_argument("--make-shipment-template", metavar="PATH", help="Write a blank shipment.json and exit")
    args = ap.parse_args()

    if args.make_shipment_template:
        write_shipment_template(args.make_shipment_template)
        return

    if not args.annexure or not args.template:
        ap.error("--annexure and --template are required (unless using --make-shipment-template)")

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"Reading annexure: {args.annexure}")
    rows, sheet_name, col_map, score = parse_annexure(args.annexure)
    if not rows:
        print("No usable rows found — check the annexure has the required columns.", file=sys.stderr)
        sys.exit(1)
    print(f"  Parsed {len(rows)} rows from sheet '{sheet_name}' "
          f"({score}/{len(REQUIRED_FIELDS)} required columns matched)")

    msds_docs = []
    for p in args.msds:
        print(f"Reading MSDS: {p}")
        msds_docs.append({"name": Path(p).name, "text": extract_pdf_text(p)})

    cert_docs = []
    for p in args.certs:
        print(f"Reading UN certificate: {p}")
        text = extract_pdf_text(p)
        info = extract_cert_info(text)
        cert_docs.append({"name": Path(p).name, "text": text, "info": info})

    today = date.today()
    results = run_verification(rows, msds_docs, cert_docs, today)
    print_verification_report(results)

    print("\nActive grouping sequence:")
    for i, (label, cond) in enumerate(CHECKPOINTS, 1):
        print(f"  {i}. {label} \u2014 {cond}")
    print(f"  (flash point threshold = {args.threshold}\u00b0C)")

    groups = compute_groups(rows, args.threshold)
    print(f"\n{len(groups)} declaration group(s) from {len(rows)} annexure rows.\n")

    shipment = load_shipment(args.shipment)
    if not args.shipment:
        print("No --shipment file given — vessel/booking/signatory fields will be left "
              "blank in the output for manual completion.\n")

    for i, g in enumerate(groups, 1):
        print(f"DGD-{i}: UN {g['unNumber']} / {g['psn']} / Class {g['hazClass']} "
              f"\u2014 {g['outerPackages']}"
              + (f", {g['innerPacking']}" if g["innerPacking"] else "")
              + f" \u2014 {g['grossWt']} / {g['netWt']}")
        print(f"        products: {', '.join(g['materials'])}")
        wb = build_dgd_workbook(args.template, g, shipment)
        out_path = out_dir / f"DGDI-{i}.xlsx"
        wb.save(out_path)
        print(f"        \u2192 saved {out_path}")

    print(f"\nDone. {len(groups)} file(s) written to {out_dir.resolve()}")


if __name__ == "__main__":
    main()
