def extract_msds_identifiers(text):
    ids = set()
    m = re.search(r"Product identifier\s*:?\s*\n?([A-Za-z0-9\-]{2,20})", text, re.I)
    if m:
        ids.add(m.group(1).strip())
    m = re.search(r"Other means of[\s\S]{0,20}identification\s*:?\s*\n?([0-9A-Za-z;,\s]{4,60})", text, re.I)
    if m:
        for tok in re.split(r"[;,]", m.group(1)):
            tok = tok.strip()
            if tok:
                ids.add(tok)
    return list(ids)


def match_msds_to_row(msds_text, row):
    ids = [norm(i) for i in extract_msds_identifiers(msds_text)]
    desc_norm = norm(row["materialDescription"])
    for idn in ids:
        if not idn:
            continue
        if idn in desc_norm or norm(row["productCode"]) == idn:
            return True
    return False


def get_section14_block(text):
    m = re.search(r"Section\s*14", text, re.I)
    if not m:
        return text
    after = text[m.start():]
    m2 = re.search(r"Section\s*1[56]", after, re.I)
    return after if not m2 else after[:m2.start()]


def extract_flash_number(s):
    m = re.search(r"-?\d+(\.\d+)?", str(s))
    return float(m.group(0)) if m else None


def verify_msds_against_row(msds_text, row):
    block = get_section14_block(msds_text)
    block_upper = block.upper()
    checks = []

    un_digits = re.sub(r"\D", "", row["unNumber"])
    checks.append({
        "field": "UN Number",
        "ok": bool(re.search(r"UN\s?0*" + re.escape(un_digits) + r"\b", block)),
        "expected": row["unNumber"],
    })

    psn_ok = bool(row["psn"]) and row["psn"].upper() in block_upper
    checks.append({"field": "Proper shipping name", "ok": psn_ok, "expected": row["psn"]})

    cls_token = row["hazClass"].replace(" ", "")
    cls_ok = bool(re.search(r"(^|[^0-9.])" + re.escape(cls_token) + r"([^0-9]|$)", block))
    checks.append({"field": "Hazard class", "ok": cls_ok, "expected": row["hazClass"]})

    pg_ok = bool(row["pkgGroup"]) and bool(re.search(r"\b" + re.escape(row["pkgGroup"].upper()) + r"\b", block_upper))
    checks.append({"field": "Packing group", "ok": pg_ok, "expected": row["pkgGroup"]})

    mp_expected = "YES" if row["marinePollutant"] == "YES" else "NO"
    mp_ok = ("YES" in block_upper) if mp_expected == "YES" else bool(re.search(r"\bNO\.?\b", block_upper))
    checks.append({"field": "Marine pollutant", "ok": mp_ok, "expected": mp_expected})

    fp_match = re.search(r"Flash point\s*:?[\s\S]{0,60}", msds_text, re.I)
    fp_msds = extract_flash_number(fp_match.group(0)) if fp_match else None
    fp_row = extract_flash_number(row["flashPoint"])
    fp_ok = (fp_msds is not None and fp_row is not None and abs(fp_msds - fp_row) <= 1.0)
    detail = row["flashPoint"] + (f" (MSDS: {fp_msds}\u00b0C)" if fp_msds is not None else " (not found in MSDS)")
    checks.append({"field": "Flash point", "ok": fp_ok, "expected": detail})

    return checks


