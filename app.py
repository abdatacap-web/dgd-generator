    set_cell(ws, SHIPMENT_CELLS["signatoryCompanyBottom"], sh("signatoryCompany"))
    set_cell(ws, SHIPMENT_CELLS["placeDateShipper"], sh("placeDate"))
    set_cell(ws, SHIPMENT_CELLS["shipperSignatory"], sh("shipperSignatory"))

    return wb


