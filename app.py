def norm(s):
    return re.sub(r"[^a-z0-9]", "", str(s or "").lower())


def match_columns(headers):
    """Fuzzy-match a header row against the required/known field synonyms."""
    normed = [norm(h) for h in headers]
    used = set()
    result = {}
    for field, syns in FIELD_SYNONYMS.items():
        best = -1
        # exact match pass
        for syn in syns:
            for i, h in enumerate(normed):
                if h == syn and i not in used:
                    best = i
                    break
            if best != -1:
                break
        # substring pass
        if best == -1:
            for syn in syns:
                for i, h in enumerate(normed):
                    if syn in h and i not in used:
                        best = i
                        break
                if best != -1:
                    break
        if best != -1:
            result[field] = best
            used.add(best)
    return result


def pick_best_sheet(wb):
    """Scan every sheet's first few rows for the header row that best matches
    the required fields, and return (sheet_name, header_row_idx, col_map, score)."""
    best = {"name": None, "score": -1, "header_row": -1, "map": {}}
    for ws in wb.worksheets:
        rows = list(ws.iter_rows(min_row=1, max_row=5, values_only=True))
        for r_idx, row in enumerate(rows):
            headers = [("" if c is None else str(c)) for c in row]
            col_map = match_columns(headers)
            score = sum(1 for f in REQUIRED_FIELDS if f in col_map)
            if score > best["score"]:
                best = {"name": ws.title, "score": score, "header_row": r_idx, "map": col_map}
    return best


def _f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def parse_annexure(path):
    """Parse the Annexure workbook. Returns (rows, sheet_name, col_map, score)."""
    wb = openpyxl.load_workbook(path, data_only=True)
    best = pick_best_sheet(wb)
    if best["name"] is None:
        return [], None, {}, 0
    ws = wb[best["name"]]
    col_map = best["map"]
    all_rows = list(ws.iter_rows(min_row=best["header_row"] + 2, values_only=True))

    def get(row, field):
        idx = col_map.get(field)
        return row[idx] if idx is not None and idx < len(row) else None

    rows = []
    for r in all_rows:
        material = get(r, "materialDescription")
        un = get(r, "unNumber")
        if not material or not un:
            continue
        if str(material).strip().upper() == "TOTAL":
            continue
        rows.append({
            "materialDescription": str(material).strip(),
            "unNumber": str(un).strip(),
            "psn": str(get(r, "psn") or "").strip(),
            "hazClass": str(get(r, "hazClass") or "").strip(),
            "pkgGroup": str(get(r, "pkgGroup") or "").strip(),
            "marinePollutant": str(get(r, "marinePollutant") or "").strip().upper(),
            "flashPoint": str(get(r, "flashPoint") or "").strip(),
            "unCertNo1": str(get(r, "unCertNo1") or "").strip(),
            "unCertNoShort": str(get(r, "unCertNoShort") or "").strip(),
            "noOfBoxes": _f(get(r, "noOfBoxes")),
            "noInTins": _f(get(r, "noInTins")),
            "grossWt": _f(get(r, "grossWt")),
            "netWt": _f(get(r, "netWt")),
            "ems": str(get(r, "ems") or "").strip(),
            "technicalName": str(get(r, "technicalName") or "").strip(),
            "productCode": str(get(r, "productCode") or "").strip(),
        })
    return rows, best["name"], col_map, best["score"]


