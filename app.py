def run_verification(rows, msds_docs, cert_docs, today):
    """msds_docs / cert_docs: list of {"name": str, "text": str}"""
    results = []
    for row in rows:
        msds_match = None
        msds_checks = []
        for m in msds_docs:
            if match_msds_to_row(m["text"], row):
                msds_match = m
                break
        if msds_match:
            msds_checks = verify_msds_against_row(msds_match["text"], row)

        cert_match = None
        cert_checks = []
        for c in cert_docs:
            info = c.get("info")
            if info and row["unCertNoShort"] and info["shortCert"] == row["unCertNoShort"].strip():
                cert_match = c
                break
        if cert_match:
            cert_checks = verify_cert_against_row(cert_match["info"], row, today)

        all_checks = msds_checks + cert_checks
        has_error = any(not c["ok"] for c in all_checks)
        has_warning = (msds_match is None) or (cert_match is None)
        status = "ERROR" if has_error else ("WARNING" if has_warning else "OK")

        results.append({
            "row": row, "msds_match": msds_match, "cert_match": cert_match,
            "msds_checks": msds_checks, "cert_checks": cert_checks, "status": status,
        })
    return results


def print_verification_report(results):
    print("\n" + "=" * 78)
    print("VERIFICATION RESULTS")
    print("=" * 78)
    counts = {"OK": 0, "WARNING": 0, "ERROR": 0}
    for v in results:
        counts[v["status"]] += 1
        row = v["row"]
        print(f"\n[{v['status']}] {row['materialDescription']}  (UN {row['unNumber']})")
        print(f"   MSDS: {v['msds_match']['name'] if v['msds_match'] else 'not uploaded'}"
              f"   |   Cert: {v['cert_match']['name'] if v['cert_match'] else 'not uploaded'}")
        for c in v["msds_checks"]:
            if not c["ok"]:
                print(f"   \u2717 MSDS {c['field']} mismatch \u2014 expected {c['expected']}")
        for c in v["cert_checks"]:
            if not c["ok"]:
                print(f"   \u2717 Cert {c['field']} mismatch \u2014 expected {c['expected']}"
                      f"{', found ' + c['found'] if c.get('found') else ''}")
    print("\n" + "-" * 78)
    print(f"Summary: {counts['OK']} OK, {counts['WARNING']} warning, {counts['ERROR']} error"
          f"  (of {len(results)} rows)")
    print("-" * 78)


